import locale
import re
import os
import glob
import shutil

class File_Contents:
    def __init__(self, file_path):
        self.file_path = file_path
        self.file_name = self.get_file_name()
        self.contents = self.file_contents()
        self.color, self.t_result = self.get_color_and_tresult()
        self.new_filename = self.new_file_name()

        #print(file_path)

    def file_contents(self):
        with open(self.file_path, 'r', encoding="cp932") as f:
            contents = f.read()
            #print(contents)
            return contents

    # ファイル名を取得する関数
    def get_file_name(self):
        file_name = os.path.basename(self.file_path)
        # ファイル名を拡張子より前の部分と後の部分に分けて左辺の2つの変数に代入する。
        serial_number, _ = os.path.splitext(file_name)
        return serial_number


    # colorとtest_resultを取得する関数
    def get_color_and_tresult(self):
      # "Color:"とその後に続くスペース・タブ(複数可、改行はまたがない)を読み飛ばし、
      # その直後にある空白以外の文字から始まる同一行内の文字列ひとまとまりをcolorへ代入する。
      # 改行を越えて次の行へ行くことはない。
      # Color値が空欄（"Color:"の直後が改行やスペースのみで終わる）の場合は\SにマッチせずmがNoneになるため、
      # 次のNoneチェックで例外を送出できる。
      # \S は「空白文字ではない1文字」を要求。
      # .* は \S で拾った1文字に続けて、同じ行の残りを貪欲に取り込みます。
        m = re.search(r"Color:[ \t]*(\S.*)", self.contents)
        # mがNoneだったらエラー表示をする。
        if not m:
            raise ValueError(f"[ERROR]: {self.file_name}")
        color = m.group(1)

        # "Test result:"とその後に続くスペース(複数可)の後ろに来る文字列ひとまとまりをt_resultへ代入する。
        n = re.search(r"Test result:\s*(.+)", self.contents)
        # nがNoneかまたはn.group(1)が"Pass"でも"Fail"でもなければエラーを表示する。
        if not n or n.group(1) not in ("Pass", "Fail"):
            raise ValueError(f"[ERROR]: {self.file_name}")
        t_result = n.group(1)

        return color, t_result

    # ファイル名を変更する関数
    def new_file_name(self):
        return f"{self.file_name}_{self.color}_{self.t_result}.txt"


    def get_contents(self):
        return self.contents


# ▼▼▼ ここを自分の環境に合わせて書き換えてください ▼▼▼
TARGET_DIR = "."  # 走査したいフォルダのパス
PATTERN = "ABC*.txt"  # 探したいファイル名のパターン（* は「何でもよい」という意味）
# ▲▲▲ ここまで ▲▲▲

found_files = ""
error_list = []
contents_list = []

def main():

# Step.1 処理対象ディレクトリ内から「ABC*.txt」に一致するファイルを走査し、一覧を取得する（対象件数を固定値にしない）。
    # 1. 指定したフォルダが本当に存在するか確認する
    if not os.path.isdir(TARGET_DIR):
        print(f"エラー: フォルダが見つかりません -> {TARGET_DIR}")
        return

    # 2. フォルダのパスとパターンをつなげて、検索用の文字列を作る
    #    例: "C:\Users\your_name\Documents\target_folder\ABC*.txt"
    search_path = os.path.join(TARGET_DIR, PATTERN)

    # 3. glob.glob() でパターンに一致するファイルを検索する
    #    見つかったファイルのパスが「リスト（一覧）」として返ってくる
    # Pythonの関数内では、外側の変数を「新しい値に置き換える（=で代入する）」時だけglobalが必要
    global found_files
    found_files = glob.glob(search_path)
    # ファイル名順（昇順）に並べ替える
    found_files = sorted(found_files)

    # 4. 見つかったファイルを1件ずつ表示する
    print("--- 見つかったファイル一覧 ---")
    for file_path in found_files:
        print(file_path)

    # 5. 件数を表示する（固定の数字ではなく、リストの長さ len() でその場で計算）
    count = len(found_files)
    print("-----------------------------")
    print(f"該当件数: {count} 件")

# Step.2 一覧の各ファイルについてFile_Contentsをインスタンス化する。
# インスタンス化中に例外が発生した場合は、元のファイル名をerror_listに追加し、
# そのファイルの以降の処理はスキップして次のファイルへ進む。
    for file in found_files:
        try:
            fc = File_Contents(file)
            contents_list.append(fc)
        except ValueError:
            #print(f"[ERROR] {os.path.basename(file)}")
            error_list.append(file)

# Step.3 例外が発生しなかったファイルについて、os.renameで元のファイル名をnew_filenameへリネームする。
# リネーム自体が失敗した場合（リネーム先が既に存在する等）も、元のファイル名をerror_listに追加する。
    for fc in contents_list:
        try:
            # os.path.dirname(パス) -> パスからディレクトリ部分だけを取り出す。
            # os.path.join(パス1, パス2, ...)複数のパスの断片を、
            # OSに応じた正しい区切り文字（Windowsなら\、Linux/Macなら/）でつなげる。
            new_path = os.path.join(os.path.dirname(fc.file_path), fc.new_filename)
            # os.rename('old_name', 'new_name')でファイル名を変更する。
            os.rename(fc.file_path, new_path)
            print(f"{fc.file_path} -> {new_path}")
            fc.file_path = new_path
        except OSError:
            #print(f"[ERROR]: {fc.file_name}")
            error_list.append(fc.file_path)

# Step. 4 全ファイルのリネーム処理が終わった後、スクリプトと同じディレクトリ直下に
# 「Pass」「Fail」フォルダを作成する。フォルダが既に存在する場合はエラーとせずそのまま使用する。
# （os.makedirsをexist_ok=Trueで呼び出す）
    pass_dir = os.path.join(TARGET_DIR, "Pass")
    fail_dir = os.path.join(TARGET_DIR, "Fail")

    os.makedirs(pass_dir, exist_ok=True)
    os.makedirs(fail_dir, exist_ok=True)

# Step.5 リネーム後のファイル名を対象に、ファイル名に"Pass"という文字列を含むかどうかを判定する関数を作成する。
# "Pass"を含む場合は「Pass」フォルダへ、"Fail"を含む場合は「Fail」フォルダへ、
# shutil.moveで移動する。移動対象はStep.3でリネームに成功したファイルのみとし、error_listに含まれるファイルは対象外とする。
# setはPythonの組み込みデータ型の1つで、「重複を持たない、順序を持たない要素の集合」です。
# setの場合、先頭から順に探索ではなく、その値に対して直接目的地として探索に行ける。
    error_set = set(error_list)

    for fc in contents_list:
        if fc.file_path in error_set:
            continue
        if "Pass" in fc.new_filename:
            shutil.move(fc.file_path, os.path.join(pass_dir, fc.new_filename))
        elif "Fail" in fc.new_filename:
            shutil.move(fc.file_path, os.path.join(fail_dir, fc.new_filename))


# Step.6 全ファイルの処理が終わった時点でerror_listを確認する。
# ・error_listが空の場合：コンソールに"File_Rename Complete!"と表示する。
# ・error_listに1件以上ある場合：Complete!は表示せず、
# error_list内の各ファイル名について"[ERROR]: <ファイル名>"の形式で1件ずつ表示する。
    if not error_list:
        print("File_Rename Complete!")
    else:
        for error in error_list:
            print(f"[ERROR]: {os.path.basename(error)}")



# このファイルを直接実行したときだけ main() を呼び出す、というお決まりの書き方
if __name__ == "__main__":
    main()