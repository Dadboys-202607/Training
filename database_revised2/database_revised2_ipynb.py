from openpyxl import load_workbook
from openpyxl.styles import Border
import openpyxl
import shutil
import os
import sys


# "住民台帳"シートから住民情報ディクショナリ(j_info)を作成して出力する関数
def get_j_info(ws):
    j_info = {}
    # (デフォルトで max_row=ws.max_row, min_col=1, max_col=ws.max_column)となる
    for row in ws.iter_rows(min_row=2, values_only=True):
        name = row[0]                    # X行目のA列:氏名をnameに格納
        j_info[name] = list(row)         # A列をキーに、B列以降のlist(row)を値にして辞書に格納
    return j_info


# 指定した住民の、指定したシートを作成する関数
def make_j_ws(jumin, ws):
    # 下から上に向かってループする
    for r in range(ws.max_row, 1, -1):
        name = ws.cell(row=r, column=1).value      # r行目のA列(氏名)をnameに格納する
        if name != jumin:     # 例: A列の氏名とjuminが一致しない場合
            ws.delete_rows(r)

    # ワークシートが"住民台帳"以外ならA,B列の3行目以降を削除
    if ws.title != "住民台帳":
        for row in range(3, ws.max_row + 1):
            for col in range(1, 3):
                ws.cell(row=row, column=col).value = None

    # 罫線をすべて削除
    for row in ws.iter_rows():
        for c in row:
            c.border = Border()


def main():
    path = "./Database.xlsx"
    wb = load_workbook(path, data_only=True)
    names = ["住民台帳", "水道料金", "電気料金", "ガス料金"]
    ws_jumin = wb["住民台帳"]

    ##### 1. Database.xlsxの内容の整合性確認 #####
    # Database.xlsx内のいずれかのシートで1行目から最終行目までの間で
    # 一つでも空白のセルがあった場合、エラー処理をする
    try:
        for ws in wb:
            for row in ws.iter_rows(values_only=True):
                # 各行でループ処理中、セルにNoneがあった場合はエラー
                if None in row:
                    raise ValueError(f"「{ws.title}」シートが不正です。Database.xlsxを再確認してください。")
    except ValueError as e:
        print(e)
        sys.exit(1)

    ##### 2. 各住民の出力エクセルの作成と保存 #####
    wb.save("Database_copy.xlsx") # data_only=Trueで開いたコピーをここで一度保存する

    # "住民台帳"シートから住民情報ディクショナリ(j_info)を作成
    j_info = get_j_info(ws_jumin)

    # 住民を一人ずつfor文でループし、出力ファイル名の作成、出力シートの作成・保存
    # j_info = j_info.keys() 同意
    for jumin in j_info:
        # 出力するエクセルの名称は"姓_名.xlsx"
        sei, mei = jumin.split()
        out_name = sei + "_" + mei
        out_excel = f"{out_name}.xlsx"
        # Database_copy.xlsx→姓_名.xlsx"という名前でコピーする
        shutil.copy("Database_copy.xlsx", out_excel)

        # 出力するエクセルをwb_tmpへ格納
        wb_tmp = load_workbook(out_excel)
        # 出力するエクセルの全シートをループして住民X(jumin)の全シートを完成させる
        for ws in wb_tmp:
            make_j_ws(jumin, ws)
        # 住民Xの出力エクセルを保存する
        wb_tmp.save(out_excel)
        print(f"{out_excel} の作成と書き込みが完了しました。")

    # 不要になった一時ファイルDatabase_copy.xlsxを削除
    os.remove("Database_copy.xlsx")


# このファイルを直接実行したときだけ main() を呼び出す、というお決まりの書き方
if __name__ == "__main__":
    main()

